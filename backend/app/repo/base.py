"""Repository interface. Reports are stored FULL (unfiltered); routes filter by role."""
from typing import Optional, Protocol


class Repo(Protocol):
    def get_user(self, email: str) -> Optional[dict]: ...
    def user_for_role(self, role: str) -> dict: ...

    def create_order(self, order: dict, submitted_by: str, report: dict) -> None: ...
    def get_order(self, order_id: str) -> Optional[dict]: ...           # {submitted_by, order, report}
    def list_orders(self, submitted_by: Optional[str] = None) -> list[dict]: ...
    def save_report(self, order_id: str, report: dict) -> None: ...

    def add_feedback(self, order_id: str, feedback: dict) -> None: ...
    def add_evidence(self, order_id: str, measurements: list[dict]) -> None: ...

    def chat_history(self, order_id: str, email: str) -> list[dict]: ...
    def add_chat(self, order_id: str, email: str, message: dict) -> None: ...
